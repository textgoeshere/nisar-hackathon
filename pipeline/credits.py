"""CREDITS.md: the canonical credits for the project.

    .venv/bin/python -m pipeline.credits            # rewrite the generated part of CREDITS.md
    .venv/bin/python -m pipeline.credits --check    # exit 1 if it is out of date (tests run this)

The top of CREDITS.md (datasets, reference sources, software, services, AI) is written by hand. The
part between the `credits:begin` / `credits:end` markers is generated here from what the site
publishes: each event's NISAR products and optical scenes (meta.json), its ground stories and its
selected media (stories.json). pipeline.stories calls write() after every build, so the per-event
table follows the editorial picks.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parent.parent
PATH = ROOT / "CREDITS.md"
BEGIN, END = "<!-- credits:begin (generated by pipeline.credits; do not edit by hand) -->", "<!-- credits:end -->"


def cell(s) -> str:
    return re.sub(r"\s+", " ", str(s or "")).replace("|", "\\|").strip()


def link(url: str | None) -> str:
    if not url:
        return ""
    return f"[{urlsplit(url).netloc.removeprefix('www.')}]({url})"


def event_rows(d: Path) -> list[tuple[str, str, str, str]]:
    meta = json.loads((d / "meta.json").read_text())
    rows, seen = [], set()
    for im in meta.get("images", []):
        src = im.get("source") or ""
        head, _, detail = src.partition(": ")
        if head in seen:
            continue
        seen.add(head)
        what = ("NISAR ground motion and coherence" if "GUNW" in head else "NISAR radar backscatter" if "GCOV" in head
                else "Optical imagery (draped ground)")
        rows.append((what, head + (f": {detail}" if detail and len(detail) < 80 else ""), "free and open (NASA Earth science data policy)"
                     if "NISAR" in head else "Copernicus Sentinel data terms (free and open, with attribution)",
                     link("https://search.asf.alaska.edu") if "NISAR" in head else link("https://earth-search.aws.element84.com/v1")))
    sp = d / "stories.json"
    if sp.exists():
        st = json.loads(sp.read_text())
        for it in st.get("items", []):
            if it.get("status") == "rejected":
                continue
            rows.append((f"Story: {it['title']}", it.get("credit") or "", it.get("licence") or "", link(it.get("page_url"))))
            if e := it.get("establishing"):
                rows.append((f"Establishing shot (not of the event): {e['title'].removeprefix('File:')}", e.get("credit") or "",
                             e.get("licence") or "", link(e.get("page_url"))))
        for it in st.get("media", []):
            rows.append((f"Media: {it.get('title')}", it.get("credit") or "", it.get("licence") or "", link(it.get("page_url"))))
    return rows


def generated() -> str:
    out = [BEGIN, "", "## Per event", "",
           "Everything each event page shows, from `site/events/<slug>/meta.json` and `stories.json`. "
           "Rejected stories are left out; media appears once an editor selects it.", ""]
    index = json.loads((ROOT / "site" / "events" / "index.json").read_text())
    slugs = [e["slug"] if isinstance(e, dict) else e for e in (index.get("events", index) if isinstance(index, dict) else index)]
    for slug in slugs:
        d = ROOT / "site" / "events" / slug
        if not (d / "meta.json").exists():
            continue
        name = json.loads((d / "meta.json").read_text()).get("name", slug)
        out += [f"### {name} (`{slug}`)", "", "| What | Credit | Licence | Source |", "|---|---|---|---|"]
        out += [f"| {cell(a)} | {cell(b)} | {cell(c)} | {s} |" for a, b, c, s in event_rows(d)]
        out.append("")
    out.append(END)
    return "\n".join(out)


def render() -> str:
    text = PATH.read_text()
    i, j = text.index(BEGIN), text.index(END) + len(END)
    return text[:i] + generated() + text[j:]


def write() -> bool:
    new = render()
    if new != PATH.read_text():
        PATH.write_text(new)
        return True
    return False


if __name__ == "__main__":
    if "--check" in sys.argv:
        ok = render() == PATH.read_text()
        print("CREDITS.md up to date" if ok else "CREDITS.md is stale: run .venv/bin/python -m pipeline.credits")
        sys.exit(0 if ok else 1)
    print("CREDITS.md updated" if write() else "CREDITS.md unchanged")
