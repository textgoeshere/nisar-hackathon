"""Static event pages: python3 scripts/pages.py

site/event.html is the one template (it also works as event.html?e=<slug>). This writes a copy per live
event to site/e/<slug>.html with its own <title>, description and Open Graph tags, so every event has an
indexable URL, and site/index.html, the landing page, as the Kumamoto event. Rerun after adding an event
or editing event.html; the output is committed.
"""
import html
import json
import re
from pathlib import Path

SITE = Path(__file__).resolve().parent.parent / "site"
URL = "https://textgoeshere.github.io/nisar-hackathon/"
HOME = "kumamoto-quake"
TAGLINE = "groundstory"


def describe(slug, meta):
    stories = SITE / "events" / slug / "stories.json"
    text = json.loads(stories.read_text()).get("boundary") if stories.exists() else None
    text = text or meta.get("note") or (f"{meta['name']}: NISAR L-band radar (NASA/ISRO) shows the boundary in the ground "
                                        "that explains what happened to the people standing on it.")
    text = re.sub(r"\s+", " ", text).strip()
    if len(text) > 160:
        text = text[:157].rsplit(" ", 1)[0].rstrip(",;:") + "…"
    return text


def head(slug, meta, path):
    e = lambda s: html.escape(s, quote=True)
    title, desc = f"{meta['name']} · {TAGLINE}", describe(slug, meta)
    image = f"{URL}events/{slug}/{meta['ground']}" if meta.get("ground") else None
    return "\n".join(filter(None, [
        f"<title>{e(title)}</title>",
        f'<meta name="description" content="{e(desc)}">',
        f'<link rel="canonical" href="{URL}{path}">',
        f'<meta property="og:type" content="website">',
        f'<meta property="og:site_name" content="{TAGLINE}">',
        f'<meta property="og:title" content="{e(title)}">',
        f'<meta property="og:description" content="{e(desc)}">',
        f'<meta property="og:url" content="{URL}{path}">',
        image and f'<meta property="og:image" content="{image}">',
        f'<meta name="twitter:card" content="{"summary_large_image" if image else "summary"}">',
    ]))


def page(template, slug, meta, path, base):
    out = re.sub(r"<!-- page:head.*?<!-- /page:head -->", lambda _: head(slug, meta, path), template, count=1, flags=re.S)
    out = out.replace('<body class="ev" data-slug="">', f'<body class="ev" data-slug="{slug}">', 1)
    if base:
        out = out.replace('<meta charset="utf-8">', f'<meta charset="utf-8">\n<base href="{base}">', 1)
    note = "<!-- Generated by scripts/pages.py from event.html: edit that and rerun. -->\n"
    return out.replace("<!doctype html>\n", "<!doctype html>\n" + note, 1)


def main():
    template = (SITE / "event.html").read_text()
    assert "<!-- page:head" in template and 'data-slug=""' in template, "event.html is missing the page markers"
    slugs = json.loads((SITE / "events" / "index.json").read_text())
    (SITE / "e").mkdir(exist_ok=True)
    for old in (SITE / "e").glob("*.html"):
        if old.stem not in slugs:
            old.unlink()
    for slug in slugs:
        meta = json.loads((SITE / "events" / slug / "meta.json").read_text())
        (SITE / "e" / f"{slug}.html").write_text(page(template, slug, meta, f"e/{slug}.html", "../"))
        if slug == HOME:
            (SITE / "index.html").write_text(page(template, slug, meta, "", None))
    print(f"wrote index.html and {len(slugs)} pages in site/e/")


if __name__ == "__main__":
    main()
